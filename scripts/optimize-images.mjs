#!/usr/bin/env node
/**
 * Image pipeline for the portfolio.
 *
 * 1. Re-encodes raster project screenshots (PNG/JPG) referenced in
 *    src/data/projects.ts to WebP and rewrites their paths in that file.
 * 2. Generates src/data/image-meta.ts with a tiny blur placeholder and the
 *    dominant colour of every project image plus the hero portrait, so
 *    components can paint something meaningful before the full image arrives.
 *
 * Usage: npm run images
 */
import { readFile, writeFile, unlink, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const projectsFile = path.join(root, "src/data/projects.ts");
const metaFile = path.join(root, "src/data/image-meta.ts");
const publicDir = path.join(root, "public");
const extraImages = ["/images/elvin-editorial.webp"];
const MAX_WIDTH = 1600;

const kb = (bytes) => `${Math.round(bytes / 1024)} KB`;

async function reencode(source) {
  const input = path.join(publicDir, source);
  const target = source.replace(/\.(png|jpe?g)$/i, ".webp");
  const output = path.join(publicDir, target);
  const before = (await stat(input)).size;
  await sharp(input)
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .webp({ quality: 82, effort: 6, smartSubsample: true })
    .toFile(output);
  const after = (await stat(output)).size;
  await unlink(input);
  console.log(`  ${source} ${kb(before)} -> ${target} ${kb(after)}`);
  return target;
}

async function describe(source) {
  const input = path.join(publicDir, source);
  const image = sharp(input);
  const { width, height } = await image.metadata();
  const { dominant } = await image.stats();
  const blur = await sharp(input).resize(16).webp({ quality: 40 }).toBuffer();
  const hex = `#${[dominant.r, dominant.g, dominant.b].map((value) => value.toString(16).padStart(2, "0")).join("")}`;
  return { width, height, color: hex, blurDataURL: `data:image/webp;base64,${blur.toString("base64")}` };
}

let projects = await readFile(projectsFile, "utf8");
const referenced = [...new Set([...projects.matchAll(/image: "([^"]+)"/g)].map((match) => match[1]))];

console.log("Re-encoding raster screenshots:");
for (const source of referenced.filter((file) => /\.(png|jpe?g)$/i.test(file))) {
  const target = await reencode(source);
  projects = projects.replaceAll(`"${source}"`, `"${target}"`);
}
await writeFile(projectsFile, projects);

console.log("Generating image metadata:");
const all = [...new Set([...projects.matchAll(/image: "([^"]+)"/g)].map((match) => match[1]).concat(extraImages))].filter((file) => !file.endsWith(".svg"));
const entries = [];
for (const source of all) {
  entries.push([source, await describe(source)]);
  console.log(`  ${source}`);
}

const body = entries.map(([source, meta]) => `  ${JSON.stringify(source)}: ${JSON.stringify(meta)},`).join("\n");
await writeFile(
  metaFile,
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand; run \`npm run images\`.\n` +
    `export type ImageMeta = { width: number; height: number; color: string; blurDataURL: string };\n\n` +
    `export const imageMeta: Record<string, ImageMeta> = {\n${body}\n};\n\n` +
    `export function getImageMeta(source: string): ImageMeta | undefined {\n  return imageMeta[source];\n}\n`,
);
console.log(`Wrote ${path.relative(root, metaFile)}`);
